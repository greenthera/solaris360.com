// Production-preview checks; lead submissions are intercepted so no test data reaches Google.
import { chromium } from 'playwright'
import assert from 'node:assert/strict'
import fs from 'node:fs/promises'
import os from 'node:os'
import path from 'node:path'
const base = (process.env.SUBSIDY_TEST_BASE_URL || 'http://127.0.0.1:4173/').replace(/\/?$/, '/')
const artifacts = await fs.mkdtemp(path.join(os.tmpdir(), 'solaris-subsidy-check-'))
const browser = await chromium.launch()
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true, reducedMotion: 'reduce' })
  await context.addInitScript(() => sessionStorage.setItem('sol_boot', '1'))
  await context.route('https://www.googletagmanager.com/**', route => route.abort())
  const leads = []
  await context.route('https://docs.google.com/forms/**', async route => {
    leads.push(new URLSearchParams(route.request().postData()))
    await route.fulfill({ status: 200, body: '' })
  })
  const page = await context.newPage(), errors = [], assetErrors = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('response', response => { if (response.url().startsWith(base) && response.status() >= 400) assetErrors.push(response.url()) })
  let downloads = 0
  page.on('download', () => downloads++)
  await page.goto(`${base}gujarat-solar-subsidy-calculator/`, { waitUntil: 'networkidle' })
  await page.locator('#boot').waitFor({ state: 'detached' })
  assert.equal(await page.locator('h1').count(), 1)
  assert.match(await page.title(), /Gujarat Solar Subsidy Calculator 2026/)
  assert.equal(await page.locator('link[rel=canonical]').getAttribute('href'), 'https://solaris360.com/gujarat-solar-subsidy-calculator/')
  assert.match(await page.locator('meta[name=description]').getAttribute('content'), /PM Surya Ghar/)
  const stats = page.locator('.subsidy-stat > p')
  const checkStats = async (central, state, youPay) => assert.deepEqual((await stats.allTextContents()).map(s => s.replace(/[₹,\s]/g, '')), [central, state, youPay].map(String))
  await checkStats(60000, 30000, 10000)
  const downloadButton = page.getByRole('button', { name: 'Download subsidy estimate (PDF)', exact: true })
  await downloadButton.click()
  assert.equal(await page.locator('[aria-invalid=true]').count(), 3)
  assert.equal(await page.locator('input[autocomplete=name]').evaluate(e => e === document.activeElement), true)
  assert.equal(leads.length, 0); assert.equal(downloads, 0)
  await page.locator('input[autocomplete=name]').fill('Subsidy Test User')
  await page.locator('input[autocomplete=tel]').fill('123')
  await page.locator('input[autocomplete=email]').fill('invalid')
  await downloadButton.click()
  assert.equal(await page.locator('[aria-invalid=true]').count(), 2)
  await page.locator('input[autocomplete=tel]').fill('+91 98765 43210')
  await page.locator('input[autocomplete=email]').fill('subsidy-test@example.com')
  const downloadEvent = page.waitForEvent('download')
  await downloadButton.click()
  const report = await downloadEvent
  await report.saveAs(path.join(artifacts, 'subsidy-report.pdf'))
  assert.equal(report.suggestedFilename(), 'solaris360-gujarat-solar-subsidy-estimate.pdf')
  assert.ok((await fs.stat(path.join(artifacts, 'subsidy-report.pdf'))).size > 10000)
  assert.equal(leads.length, 1)
  assert.equal(leads[0].get('entry.764862047'), 'Gujarat solar subsidy calculator')
  assert.equal(leads[0].get('entry.1840546608'), 'subsidy-test@example.com')
  assert.equal(leads[0].get('entry.1409510977'), '9876543210')
  assert.match(leads[0].get('entry.958728776'), /Total subsidy: ₹ 90,000/)
  await page.getByRole('button', { name: 'SC / ST', exact: true }).click()
  await checkStats(60000, 35000, 5000)
  const capacity = page.getByRole('spinbutton', { name: 'New system capacity (DC)', exact: true })
  await capacity.fill('2.18'); await checkStats(63240, 39455, 5405)
  await capacity.fill('2.19'); assert.equal((await stats.nth(1).textContent()).replace(/[₹,\s]/g, ''), '0')
  await page.getByRole('button', { name: 'Reset calculator', exact: true }).click()
  await page.getByLabel('Vendor quotation', { exact: true }).fill('120000'); await checkStats(60000, 30000, 30000)
  await page.getByLabel('Vendor quotation', { exact: true }).fill('0')
  assert.equal(await downloadButton.isDisabled(), true)
  await page.getByLabel('Vendor quotation', { exact: true }).fill('')
  await capacity.fill('3')
  await page.getByRole('spinbutton', { name: 'Solar already installed', exact: true }).fill('1')
  assert.equal((await stats.nth(0).textContent()).replace(/[₹,\s]/g, ''), '48000')
  await page.getByLabel('The existing system received central subsidy', { exact: true }).uncheck()
  assert.equal((await stats.nth(0).textContent()).replace(/[₹,\s]/g, ''), '78000')
  await page.getByRole('button', { name: 'Reset calculator', exact: true }).click()
  await page.getByLabel('Residential electricity consumer in Gujarat', { exact: true }).uncheck(); await checkStats(0, 0, 100000)
  await page.getByLabel('Residential electricity consumer in Gujarat', { exact: true }).check()
  await page.getByLabel('Commissioned on/after 22 October 2026, or installation is planned', { exact: true }).uncheck(); await checkStats(60000, 0, 40000)
  await page.getByRole('button', { name: 'Reset calculator', exact: true }).click()
  await page.getByRole('spinbutton', { name: 'Your electricity rate (for payback)', exact: true }).fill('0')
  assert.match(await page.locator('.subsidy-table-scroll').innerText(), /Not available at ₹0/)
  await page.getByRole('button', { name: 'Reset calculator', exact: true }).click()
  await page.locator('.subsidy-advanced summary').click()
  await page.getByLabel('General contribution', { exact: true }).fill('20'); await checkStats(60000, 20000, 20000)
  assert.match(await page.locator('.subsidy-alert').innerText(), /Custom rates/)
  await page.getByLabel('General contribution', { exact: true }).fill('101')
  assert.equal(await downloadButton.isDisabled(), true)
  await page.getByRole('button', { name: 'Reset to default rates', exact: true }).click(); await checkStats(60000, 30000, 10000)
  await page.locator('.subsidy-chart circle[tabindex]').first().focus()
  assert.match(await page.locator('.subsidy-chart-readout').innerText(), /Central subsidy/)
  for (const width of [320, 390, 768, 1440]) {
    await page.setViewportSize({ width, height: 900 })
    await page.evaluate(async () => { for (let y = 0; y < document.body.scrollHeight; y += 600) { window.scrollTo(0, y); await new Promise(resolve => setTimeout(resolve, 20)) } window.scrollTo(0, 0) })
    await page.screenshot({ path: path.join(artifacts, `subsidy-${width}.png`), fullPage: true })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false, `Overflow at ${width}`)
  }
  assert.deepEqual(assetErrors, []); assert.deepEqual(errors, [])
  console.log(`PASS: subsidies, category and capacity boundaries, existing aid, quotations, rates/reset, eligibility, required contact gate, intercepted lead payload, PDF, chart and four viewport widths.\nArtifacts: ${artifacts}`)
} finally { await browser.close() }
